#!/usr/bin/env node
/**
 * Downloads bank logos into assets/banks/ and writes src/ui/theme/bankLogos.generated.ts.
 * Both are gitignored: bank logos are trademarks of their owners and are not covered by
 * PennyTrace's AGPL licence, so they are fetched for your own builds and never committed.
 * Without them the app shows coloured initials tiles.
 *
 * This runs on your computer at development time. The app itself never downloads anything
 * except the on-device model.
 *
 *   node scripts/fetch-bank-logos.js
 *
 * Sources: the logo file on the bank's Wikipedia article (rendered to PNG by Wikimedia), or the
 * bank's Play Store app icon when the app icon *is* the brand mark (slice). Wordmark logos are
 * wide, so each one names the crop (fractions of the image) that holds the symbol; tiles show
 * only that part.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'banks');
const REGISTRY = path.join(ROOT, 'src', 'ui', 'theme', 'bankLogos.generated.ts');
const UA = 'PennyTrace-dev/0.1 (scripts/fetch-bank-logos.js)';

/** Parser bank id → logo source. `crop` = [x, y, w, h] as fractions of the image. */
const BANKS = {
  hdfc: { wiki: 'File:HDFC Bank Logo.svg', crop: [0, 0, 0.17, 1] },
  sbi: { wiki: 'File:SBI-logo.svg' },
  bob: { wiki: 'File:BankOfBarodaLogo.svg', crop: [0.008, 0.033, 0.285, 0.711] },
  canara: { wiki: 'File:Canara bank logo.svg', crop: [0.852, 0.018, 0.148, 0.502] },
  icici: { wiki: 'File:ICICI Bank Logo.svg', crop: [0, 0, 0.191, 1] },
  axis: { wiki: 'File:AXISBank Logo.svg', crop: [0.004, 0.029, 0.297, 0.946] },
  kotak: { wiki: 'File:Kotak Mahindra Bank logo.svg', crop: [0.016, 0.072, 0.293, 0.879] },
  // The app icon is slice's brand mark and fills the tile edge to edge.
  slice: { play: ['indwin.c3.shareapp', 'slice'], bleed: true },
};

async function get(url) {
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) {
    throw new Error(`${res.status} for ${url}`);
  }
  return res;
}

async function wikiPngUrl(file) {
  const api =
    'https://en.wikipedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=url&iiurlwidth=1100&titles=' +
    encodeURIComponent(file);
  const data = await (await get(api)).json();
  const page = Object.values(data.query.pages)[0];
  const url = page?.imageinfo?.[0]?.thumburl;
  if (!url) {
    throw new Error(`no rendered PNG for ${file}`);
  }
  return url;
}

async function playIconUrl(pkg, mustContain) {
  const html = await (await get(`https://play.google.com/store/apps/details?id=${pkg}&hl=en_IN`)).text();
  const title = /<meta property="og:title" content="([^"]+)"/.exec(html)?.[1] ?? '';
  const image = /<meta property="og:image" content="([^"]+)"/.exec(html)?.[1];
  if (!image || !title.toLowerCase().includes(mustContain.toLowerCase())) {
    throw new Error(`unexpected store page "${title}"`);
  }
  return `${image.replace(/=[^/]*$/, '')}=s192`;
}

/** Width and height from a PNG header. */
function pngSize(buf) {
  if (buf.subarray(1, 4).toString() !== 'PNG') {
    throw new Error('not a PNG');
  }
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const entries = [];
  for (const [id, spec] of Object.entries(BANKS)) {
    try {
      const url = spec.wiki ? await wikiPngUrl(spec.wiki) : await playIconUrl(...spec.play);
      const buf = Buffer.from(await (await get(url)).arrayBuffer());
      const { width, height } = pngSize(buf);
      fs.writeFileSync(path.join(OUT_DIR, `${id}.png`), buf);
      const crop = (spec.crop ? `, crop: [${spec.crop.join(', ')}]` : '') + (spec.bleed ? ', bleed: true' : '');
      entries.push(
        `  '${id}': { source: require('../../../assets/banks/${id}.png'), width: ${width}, height: ${height}${crop} },`,
      );
      console.log(`ok    ${id} (${width}x${height})`);
    } catch (e) {
      console.log(`skip  ${id}: ${e.message}`);
    }
  }
  fs.writeFileSync(
    REGISTRY,
    [
      '// GENERATED by scripts/fetch-bank-logos.js. Gitignored: bank logos are trademarks of their owners.',
      "import type { BankLogo } from './bankLogos';",
      '',
      'export const BANK_LOGOS: Record<string, BankLogo> = {',
      ...entries,
      '};',
      '',
    ].join('\n'),
  );
  console.log(`\n${entries.length}/${Object.keys(BANKS).length} logos → assets/banks/`);
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
